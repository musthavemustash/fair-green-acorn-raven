/** Two bits per kept face, most-significant bit first. 128 faces = 256 bits. */
var FACE_BITS = {
	1: "00",
	2: "01",
	3: "10",
	4: "11"
};
function isDieFace(value) {
	return value === 1 || value === 2 || value === 3 || value === 4;
}
/** 5 and 6 carry no entropy in this scheme. */
function isReroll(value) {
	return value === 5 || value === 6;
}
/** Append one kept face. A full record is returned unchanged so a tap cannot spill past 256 bits. */
function appendFace(rolls, face) {
	if (rolls.length >= 128) return rolls;
	return [...rolls, face];
}
function undoFace(rolls) {
	return rolls.slice(0, -1);
}
/** Repeating 1, 2, 3, 4. A known phrase, never real entropy. */
function testPattern() {
	const rolls = [];
	for (let i = 0; i < 128; i++) {
		const face = i % 4 + 1;
		rolls.push(face);
	}
	return rolls;
}
function rollsToBitString(rolls) {
	let bits = "";
	for (const face of rolls) bits += FACE_BITS[face];
	return bits;
}
function bitStringToBytes(bits) {
	if (bits.length % 8 !== 0) throw new Error("Bit string is not a whole number of bytes");
	const bytes = new Uint8Array(bits.length / 8);
	for (let i = 0; i < bytes.length; i++) bytes[i] = Number.parseInt(bits.slice(i * 8, i * 8 + 8), 2);
	return bytes;
}
async function sha256(bytes) {
	const subtle = globalThis.crypto?.subtle;
	if (!subtle) throw new Error("SHA-256 is unavailable in this browser");
	const copy = new ArrayBuffer(bytes.byteLength);
	new Uint8Array(copy).set(bytes);
	return new Uint8Array(await subtle.digest("SHA-256", copy));
}
/** Exactly 128 kept faces → BIP39 24-word mnemonic. Extra faces are not accepted. */
async function mnemonicFromRolls(rolls) {
	if (rolls.length !== 128) throw new Error(`Need exactly 128 faces`);
	const bits = rollsToBitString(rolls);
	if (bits.length !== 256) throw new Error("Entropy was not 256 bits");
	const full = bits + ((await sha256(bitStringToBytes(bits)))[0] ?? 0).toString(2).padStart(8, "0");
	const words = [];
	for (let i = 0; i < 24; i++) {
		const index = Number.parseInt(full.slice(i * 11, (i + 1) * 11), 2);
		const word = WORDLIST[index];
		if (word === void 0) throw new Error(`Word index out of range: ${index}`);
		words.push(word);
	}
	return words;
}
